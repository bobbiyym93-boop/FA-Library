export function densityChinesePlugin() {
  return {
    name: 'density-chinese-localization',
    enforce: 'pre',
    transform(code, id) {
      if (!id.endsWith('/src/components/DensityAnalysisView.vue')) return null
      let output = code
      for (const [from, to] of replacements) output = output.split(from).join(to)
      output = output
        .replace(/Analyzing (\$\{[^}]+\})\.\.\./g, '正在分析 $1...')
        .replace(/Analysis completed ·/g, '分析完成 ·')
        .replace(/ config loaded/g, ' 配置已加载')
        .replace(/Config error:/g, '配置错误：')
        .replace(/XML config exported/g, 'XML 配置已导出')
        .replace(/Current analysis added to local history view/g, '当前分析已加入本地历史记录')
        .replace(/Found (\$\{[^}]+\}) FA records/g, '找到 $1 条 FA 记录')
        .replace(/No matching FA records/g, '未找到匹配的 FA 记录')
        .replace(/FA query failed:/g, 'FA 查询失败：')
        .replace(/ FA records matched/g, ' 条 FA 记录匹配')
      return { code: output, map: null }
    },
  }
}
